const normalize = value => String(value || '').trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
const byAlias = new Map(mlbLogoAssignments236.flatMap(team => [team.code, team.name, ...team.aliases].map(alias => [normalize(alias), team])));
const byMlbId = new Map(mlbLogoAssignments236.map(team => [team.mlbId, team]));
function customLogo(value) {
  const src = String(value || '').trim();
  if (/^data:image\/(?:png|jpeg|webp);base64,/i.test(src)) return src;
  if (/^https:\/\//i.test(src)) {
    try {
      const url = new URL(src), host = url.hostname.toLowerCase();
      if (url.username || url.password) return '';
      const mlbDefault = /^(?:www\.)?mlbstatic\.com$/.test(host) && /^\/team-logos\/\d+\.(?:svg|png)$/.test(url.pathname);
      const espnDefault = /(?:^|\.)espncdn\.com$/.test(host) && /^\/(?:i\/teamlogos\/mlb\/|combiner\/i)/.test(url.pathname);
      return mlbDefault || espnDefault ? '' : src;
    } catch { return ''; }
  }
  // Local assignments are retained; never reinterpret a URL scheme or traversal.
  if (/^(?:\.\/|\/)?(?:assets|broadcast-logos\d+)\//.test(src) && !/[\\?#\x00-\x1f]/.test(src)) {
    try { if (!decodeURIComponent(src).split('/').includes('..')) return src; } catch {}
  }
  return '';
}
export function mlbBroadcastLogo236(league, team = {}, provider = '') {
  if (normalize(league) !== 'MLB') return '';
  const custom = customLogo(team.logo);
  if (custom) return custom;
  const entry = byAlias.get(normalize(team.abbr)) || byAlias.get(normalize(team.name)) ||
    (normalize(provider) === 'MLB' ? byMlbId.get(String(team.id || '')) : null);
  return entry ? new URL('./broadcast-logos236/mlb/' + entry.file, import.meta.url).href : '';
}
